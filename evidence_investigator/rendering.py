"""Formatting of the briefing: Harvard (Cite Them Right) references and Markdown.

Kept separate from the Reporting Agent so presentation can change (Markdown,
HTML, JSON) without touching agent logic, which is the layering argument made
in the proposal (section 3).
"""

from __future__ import annotations

from datetime import date

from .schemas import Appraisal, AuditEvent, Briefing, CriticVerdict, Paper

# Sentinel author meaning "list is incomplete"; forces "et al." formatting.
ET_AL = "et al."


def _initials(given: str) -> str:
    return "".join(f"{part[0]}." for part in given.replace("-", " ").split() if part)


def harvard_author(name: str) -> str:
    parts = name.split()
    if len(parts) < 2:
        return name
    return f"{parts[-1]}, {_initials(' '.join(parts[:-1]))}"


def surname(name: str) -> str:
    return name.split()[-1] if name.split() else name


def in_text(paper: Paper) -> str:
    year = paper.year or "no date"
    a = paper.authors
    truncated = ET_AL in a
    a = [x for x in a if x != ET_AL]
    if not a:
        names = paper.title.split(":")[0]
    elif len(a) == 1 and not truncated:
        names = surname(a[0])
    elif len(a) == 2 and not truncated:
        names = f"{surname(a[0])} and {surname(a[1])}"
    else:
        names = f"{surname(a[0])} et al."
    return f"{names}, {year}"


def reference(paper: Paper, accessed: date | None = None) -> str:
    accessed = accessed or date.today()
    truncated = ET_AL in paper.authors
    a = [x for x in paper.authors if x != ET_AL]
    if not a:
        authors = ""
    elif len(a) <= 3 and not truncated:
        formatted = [harvard_author(x) for x in a]
        authors = formatted[0] if len(formatted) == 1 else ", ".join(formatted[:-1]) + " and " + formatted[-1]
    else:
        authors = f"{harvard_author(a[0])} et al."
    year = paper.year or "no date"
    venue = f" {paper.venue}." if paper.venue else ""
    link = f"https://doi.org/{paper.doi}" if paper.doi else paper.url
    head = f"{authors} ({year}) " if authors else f"({year}) "
    return (f"{head}'{paper.title}',{venue} Available at: {link} "
            f"(Accessed: {accessed.day} {accessed:%B %Y}).")


def by_first_author(papers: list[Paper]) -> list[Paper]:
    """Harvard reference lists are alphabetical by first author's surname."""
    def key(p: Paper) -> tuple:
        named = [a for a in p.authors if a != ET_AL]
        return (surname(named[0]).lower() if named else p.title.lower(), p.year or 0)
    return sorted(papers, key=key)


def render_markdown(briefing: Briefing, papers: list[Paper], appraisals: dict[str, Appraisal],
                    verdict: CriticVerdict | None, audit: list[AuditEvent]) -> str:
    by_id = {p.paper_id: p for p in papers}
    cite = lambda ids: "; ".join(in_text(by_id[i]) for i in ids if i in by_id)  # noqa: E731

    lines = [f"# Research briefing", "", f"**Question:** {briefing.question}", "",
             f"**Evidence status:** {briefing.evidence_status}", "",
             f"_Generated by: {briefing.generated_by} reporting; appraisals by "
             f"{', '.join(sorted({a.method for a in appraisals.values()})) or 'n/a'}. "
             "This briefing supports, and does not replace, the researcher's own reading._", "",
             "## Summary", "", briefing.summary, "", "## Key findings", ""]
    lines += [f"- {k.statement} ({cite(k.paper_ids)})" for k in briefing.key_findings]
    for heading, items in (("Conflicting or inconclusive evidence", briefing.conflicting_evidence),
                           ("Limitations", briefing.limitations),
                           ("Possible research opportunities (within retrieved evidence only)",
                            briefing.research_opportunities)):
        lines += ["", f"## {heading}", ""] + ([f"- {i}" for i in items] or ["- None identified."])

    lines += ["", "## Evidence table", "", "| Source | Design | Stance | Relevance |",
              "|---|---|---|---|"]
    for p in papers:
        a = appraisals.get(p.paper_id)
        if a:
            lines.append(f"| {in_text(p)} | {a.study_design} | {a.stance} | {p.relevance:.2f} |")

    lines += ["", "## Audit trail", ""]
    lines += [f"- [cycle {e.cycle}] **{e.agent}** {e.action}: {e.detail}" for e in audit]
    lines += ["", "## References", ""]
    lines += [reference(p) for p in by_first_author(papers)]
    return "\n".join(lines) + "\n"
